import { afterEach, describe, expect, it, vi } from 'vitest'
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter } from 'react-router-dom'
import { SummaryPage } from './SummaryPage'
import { useWallet } from '../lib/wallet'
import type { WalletContextValue } from '../lib/wallet'
import {
  createMockClient,
  MOCK_PATIENT_ADDRESS,
  SorobanClientProvider,
  type LockaContractClient,
} from '../lib/soroban'
import { PatientSummaryProvider, type PatientSummary, type PatientSummaryClient } from '../lib/summary'

vi.mock('../lib/wallet', async () => {
  const actual = await vi.importActual<typeof import('../lib/wallet')>('../lib/wallet')
  return { ...actual, useWallet: vi.fn() }
})

const SUMMARY: PatientSummary = {
  patientId: 'passport-7f3a91',
  summary: 'Recent records include a full blood count within its reference range.',
  generatedAt: '2026-10-12T09:30:00.000Z',
  recordCount: 2,
}

function mockWallet(overrides: Partial<WalletContextValue> = {}) {
  vi.mocked(useWallet).mockReturnValue({
    address: MOCK_PATIENT_ADDRESS,
    network: 'TESTNET',
    networkPassphrase: 'Test SDF Network ; September 2015',
    expectedNetworkPassphrase: 'Test SDF Network ; September 2015',
    isInstalled: true,
    isDetecting: false,
    isConnecting: false,
    isConnected: true,
    isWrongNetwork: false,
    error: null,
    connect: vi.fn(),
    disconnect: vi.fn(),
    ...overrides,
  })
}

function renderPage(
  client: PatientSummaryClient,
  contractClient: LockaContractClient = createMockClient({ latencyMs: 0 }),
) {
  return render(
    <SorobanClientProvider client={contractClient}>
      <PatientSummaryProvider client={client}>
        <MemoryRouter>
          <SummaryPage />
        </MemoryRouter>
      </PatientSummaryProvider>
    </SorobanClientProvider>,
  )
}

function disclaimer() {
  return screen.getByRole('note', { name: /ai summary disclaimer/i })
}

afterEach(() => {
  vi.mocked(useWallet).mockReset()
})

describe('SummaryPage', () => {
  it('shows a loading state while the summary is being fetched', async () => {
    mockWallet()
    let resolveSummary!: (summary: PatientSummary | null) => void
    const getSummary = vi.fn(
      () =>
        new Promise<PatientSummary | null>((resolve) => {
          resolveSummary = resolve
        }),
    )
    renderPage({ getSummary })

    expect(await screen.findByRole('status', { name: /loading ai summary/i })).toBeInTheDocument()
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)

    resolveSummary(SUMMARY)
    expect(await screen.findByText(SUMMARY.summary)).toBeInTheDocument()
    expect(getSummary).toHaveBeenCalledWith('passport-7f3a91')
  })

  it('renders the summary from locka-api with the persistent disclaimer', async () => {
    mockWallet()
    const getSummary = vi.fn().mockResolvedValue(SUMMARY)
    renderPage({ getSummary })

    expect(await screen.findByRole('heading', { name: /your health summary/i })).toBeInTheDocument()
    expect(screen.getByText(SUMMARY.summary)).toBeInTheDocument()
    expect(screen.getByText('Built from 2 approved records.')).toBeInTheDocument()
    expect(screen.getByText(/generated by locka-api on/i)).toBeInTheDocument()
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)
  })

  it('shows an empty state when there are no approved records yet', async () => {
    mockWallet()
    renderPage({ getSummary: vi.fn().mockResolvedValue(null) })

    expect(await screen.findByRole('heading', { name: /no approved records yet/i })).toBeInTheDocument()
    expect(screen.getByRole('link', { name: /review consent requests/i })).toHaveAttribute('href', '/consent')
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)
  })

  it('shows an error state when the summary API fails', async () => {
    mockWallet()
    renderPage({
      getSummary: vi.fn().mockRejectedValue(new Error('The AI summary service is unavailable.')),
    })

    expect(await screen.findByRole('heading', { name: /could not load your ai summary/i })).toBeInTheDocument()
    expect(screen.getByText('The AI summary service is unavailable.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /refresh summary/i })).toBeEnabled()
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)
  })

  it('re-fetches on refresh instead of showing a stale summary', async () => {
    mockWallet()
    const user = userEvent.setup()
    const updated: PatientSummary = {
      ...SUMMARY,
      summary: 'A new lab result was added to your approved records.',
      generatedAt: '2026-10-13T10:00:00.000Z',
      recordCount: 3,
    }
    const getSummary = vi.fn().mockResolvedValueOnce(SUMMARY).mockResolvedValueOnce(updated)
    renderPage({ getSummary })

    expect(await screen.findByText(SUMMARY.summary)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /refresh summary/i }))

    expect(await screen.findByText(updated.summary)).toBeInTheDocument()
    expect(screen.queryByText(SUMMARY.summary)).not.toBeInTheDocument()
    expect(screen.getByText('Built from 3 approved records.')).toBeInTheDocument()
    expect(getSummary).toHaveBeenCalledTimes(2)
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)
  })

  it('prompts for passport registration before requesting a summary', async () => {
    mockWallet()
    const getSummary = vi.fn()
    renderPage(
      { getSummary },
      createMockClient({ latencyMs: 0, unregistered: true }),
    )

    expect(await screen.findByRole('heading', { name: /register your passport first/i })).toBeInTheDocument()
    expect(getSummary).not.toHaveBeenCalled()
    expect(disclaimer()).toHaveTextContent(/AI-generated, not medical advice/i)
  })
})
