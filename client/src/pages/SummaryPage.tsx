import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { Badge, Button, Card, Spinner } from '../components/ui'
import {
  AI_SUMMARY_DISCLAIMER,
  usePatientSummaryClient,
  type PatientSummary,
} from '../lib/summary'
import { describeUnknownError, useSorobanClient } from '../lib/soroban'
import { useWallet } from '../lib/wallet'

type SummaryStatus = 'loading' | 'empty' | 'ready' | 'error'

interface SummaryView {
  status: SummaryStatus
  summary: PatientSummary | null
  error: string | null
  passportMissing: boolean
}

const INITIAL_STATE: SummaryView = {
  status: 'loading',
  summary: null,
  error: null,
  passportMissing: false,
}

function formatGeneratedAt(value: string | null): string | null {
  if (!value) return null
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return null
  return date.toLocaleString('en', { dateStyle: 'medium', timeStyle: 'short' })
}

function recordCountLabel(count: number | null): string {
  if (count === null) return 'Built only from records you have approved.'
  return `Built from ${count} approved record${count === 1 ? '' : 's'}.`
}

function SummaryCard({ summary }: { summary: PatientSummary }) {
  const generatedAt = formatGeneratedAt(summary.generatedAt)

  return (
    <Card className="p-6 sm:p-8">
      <div className="flex items-start justify-between gap-4 flex-wrap">
        <div>
          <h2 className="text-lg font-bold text-white">Your health summary</h2>
          <p className="mt-1 text-sm text-slate-400">{recordCountLabel(summary.recordCount)}</p>
        </div>
        <Badge color="cyan">Approved records only</Badge>
      </div>

      <div className="mt-5 whitespace-pre-line text-sm leading-6 text-slate-300">{summary.summary}</div>

      <p className="mt-5 border-t border-blue-900/30 pt-4 text-xs text-slate-500">
        {generatedAt
          ? `Generated by locka-api on ${generatedAt}.`
          : 'Generated by locka-api from your approved records.'}
      </p>
    </Card>
  )
}

export function SummaryPage() {
  const { address } = useWallet()
  const contractClient = useSorobanClient()
  const summaryClient = usePatientSummaryClient()
  const [refreshKey, setRefreshKey] = useState(0)
  const [state, setState] = useState<SummaryView>(INITIAL_STATE)

  useEffect(() => {
    if (!address) return

    let cancelled = false
    setState(INITIAL_STATE)

    async function load() {
      try {
        const passport = await contractClient.getPassport(address as string)
        if (cancelled) return

        if (!passport) {
          setState({ ...INITIAL_STATE, status: 'empty', passportMissing: true })
          return
        }

        const summary = await summaryClient.getSummary(passport.id)
        if (cancelled) return

        setState(
          summary
            ? { status: 'ready', summary, error: null, passportMissing: false }
            : { ...INITIAL_STATE, status: 'empty' },
        )
      } catch (error) {
        if (!cancelled) {
          setState({
            ...INITIAL_STATE,
            status: 'error',
            error: describeUnknownError(error),
          })
        }
      }
    }

    load()
    return () => {
      cancelled = true
    }
  }, [address, contractClient, refreshKey, summaryClient])

  const isLoading = state.status === 'loading'

  return (
    <div className="mx-auto max-w-3xl px-6 py-16">
      <div className="mb-6 flex items-start justify-between gap-4 flex-wrap">
        <div>
          <h1 className="mb-1 text-2xl font-bold text-white">AI Summary</h1>
          <p className="text-sm text-slate-400">
            An assistive overview generated by locka-api from the records you have approved.
          </p>
        </div>
        <Button
          variant="secondary"
          loading={isLoading}
          onClick={() => setRefreshKey((current) => current + 1)}
        >
          Refresh summary
        </Button>
      </div>

      <Card
        role="note"
        aria-label="AI summary disclaimer"
        className="mb-6 border border-amber-500/30 bg-amber-500/5 p-4"
      >
        <div className="flex items-start gap-3">
          <Badge color="amber">AI-generated</Badge>
          <p className="text-sm leading-6 text-amber-100/90">{AI_SUMMARY_DISCLAIMER}</p>
        </div>
      </Card>

      {isLoading && (
        <Card
          role="status"
          aria-label="Loading AI summary"
          className="flex flex-col items-center gap-3 p-10 text-center"
        >
          <Spinner size={28} />
          <p className="text-sm text-slate-400">Loading your AI summary…</p>
        </Card>
      )}

      {state.status === 'error' && (
        <Card className="p-8 text-center">
          <h2 className="mb-2 text-lg font-bold text-white">Could not load your AI summary</h2>
          <p className="text-sm text-slate-400">{state.error}</p>
        </Card>
      )}

      {state.status === 'empty' && state.passportMissing && (
        <Card className="p-8 text-center">
          <h2 className="mb-2 text-lg font-bold text-white">Register your passport first</h2>
          <p className="mb-6 text-sm text-slate-400">
            An AI summary is generated from your approved medical records, so you need a passport
            before one can be created.
          </p>
          <Link
            to="/passport/register"
            className="btn-primary inline-block rounded-lg px-5 py-2.5 text-sm font-semibold"
          >
            Register your passport
          </Link>
        </Card>
      )}

      {state.status === 'empty' && !state.passportMissing && (
        <Card className="p-8 text-center">
          <h2 className="mb-2 text-lg font-bold text-white">No approved records yet</h2>
          <p className="mx-auto mb-6 max-w-md text-sm text-slate-400">
            locka-api can only summarise records you have approved. Once you grant a provider access,
            refresh to check for a new summary.
          </p>
          <Link
            to="/consent"
            className="btn-secondary inline-block rounded-lg px-4 py-2 text-sm font-semibold"
          >
            Review consent requests
          </Link>
        </Card>
      )}

      {state.status === 'ready' && state.summary && <SummaryCard summary={state.summary} />}
    </div>
  )
}
